-- 3.5 Display a customer's basic details and order summary.
SELECT c.CustomerID,
       c.CustomerName,
       c.Email,
       c.City,
       c.State,
       c.CustomerSegment,
       c.JoinDate,
       COUNT(DISTINCT o.OrderID) AS TotalOrders
