-- =========================================================
-- TASK 1: DATABASE STRUCTURE — TABLES, PRIMARY KEYS, FOREIGN KEYS
-- =========================================================

PRAGMA foreign_keys = ON;

CREATE TABLE IF NOT EXISTS Customers (
    CustomerID       TEXT PRIMARY KEY,
    CustomerName     TEXT NOT NULL,
    City             TEXT,
    State            TEXT,
    Email            TEXT,
    CustomerSegment  TEXT,
    JoinDate         TEXT
);

CREATE TABLE IF NOT EXISTS Products (
    ProductID    TEXT PRIMARY KEY,
    ProductName  TEXT NOT NULL,
    Category     TEXT,
    UnitPrice    REAL NOT NULL CHECK (UnitPrice >= 0),
    UnitCost     REAL NOT NULL CHECK (UnitCost >= 0),
    IsActive     TEXT NOT NULL CHECK (IsActive IN ('Yes', 'No'))
);

CREATE TABLE IF NOT EXISTS Orders (
    OrderID       TEXT PRIMARY KEY,
    CustomerID    TEXT NOT NULL,
    OrderDate     TEXT NOT NULL,
    ShipCity      TEXT,
    OrderStatus   TEXT NOT NULL,
    SalesChannel  TEXT NOT NULL,
    FOREIGN KEY (CustomerID) REFERENCES Customers(CustomerID)
);

CREATE TABLE IF NOT EXISTS OrderItems (
    OrderItemID  TEXT PRIMARY KEY,
    OrderID      TEXT NOT NULL,
    ProductID    TEXT NOT NULL,
    Quantity     INTEGER NOT NULL CHECK (Quantity > 0),
    FOREIGN KEY (OrderID)   REFERENCES Orders(OrderID),
    FOREIGN KEY (ProductID) REFERENCES Products(ProductID)
);

-- Relationship summary:
--   Customers (1) ---- (many) Orders
--   Orders    (1) ---- (many) OrderItems
--   Products  (1) ---- (many) OrderItems


