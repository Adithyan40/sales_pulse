-- 6.1 CUSTOMER LIST PAGE
SELECT CustomerID, CustomerName, Email, City, State, CustomerSegment, JoinDate
FROM Customers
WHERE CustomerName LIKE ?
ORDER BY CustomerName;

-- 6.2 CUSTOMER DETAILS PAGE
SELECT c.CustomerID,
       c.CustomerName,
       c.Email,
       c.City,
       c.State,
       c.CustomerSegment,
       c.JoinDate,
       o.OrderID,
       o.OrderDate,
       o.OrderStatus,
       o.SalesChannel
FROM Customers AS c
LEFT JOIN Orders AS o ON o.CustomerID = c.CustomerID
WHERE c.CustomerID = ?
ORDER BY o.OrderDate DESC;

-- 6.3 ORDER LIST PAGE
SELECT o.OrderID,
       c.CustomerName,
       o.OrderDate,
       o.ShipCity,
       o.OrderStatus,
       o.SalesChannel
FROM Orders AS o
JOIN Customers AS c ON c.CustomerID = o.CustomerID
WHERE o.OrderStatus = ?
ORDER BY o.OrderDate DESC;

-- 6.4 ORDER DETAILS PAGE
SELECT o.OrderID,
       c.CustomerName,
       o.OrderDate,
       o.ShipCity,
       o.OrderStatus,
       o.SalesChannel,
       p.ProductName,
       oi.Quantity,
       p.UnitPrice,
       (p.UnitPrice * oi.Quantity) AS ItemRevenue
FROM Orders AS o
JOIN Customers  AS c  ON c.CustomerID = o.CustomerID
JOIN OrderItems AS oi ON oi.OrderID   = o.OrderID
JOIN Products   AS p  ON p.ProductID  = oi.ProductID
WHERE o.OrderID = ?;

-- 6.5 PRODUCT LIST PAGE
SELECT ProductID, ProductName, Category, UnitPrice, UnitCost, IsActive
FROM Products
WHERE ProductName LIKE ?
ORDER BY ProductName;

-- 6.6 SALES REPORT PAGE — basic overall sales summary
SELECT COUNT(DISTINCT o.OrderID)                    AS TotalOrders,
       SUM(oi.Quantity)                             AS TotalQuantitySold,
       SUM(p.UnitPrice * oi.Quantity)               AS TotalRevenue,
       SUM((p.UnitPrice - p.UnitCost) * oi.Quantity) AS EstimatedGrossProfit
FROM Orders AS o
JOIN OrderItems AS oi ON oi.OrderID  = o.OrderID
JOIN Products   AS p  ON p.ProductID = oi.ProductID;

