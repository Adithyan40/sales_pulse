-- 4.1 Check that the customer exists before creating the order.
SELECT CustomerID
FROM Customers
WHERE CustomerID = ?;

-- 4.2 Check that a product exists and is active.
SELECT ProductID, ProductName, UnitPrice, UnitCost, IsActive
FROM Products
WHERE ProductID = ?
  AND IsActive = 'Yes';

-- 4.3 Calculate the order total for one order.
-- ? is the OrderID supplied by the application.
SELECT oi.OrderID,
       SUM(p.UnitPrice * oi.Quantity) AS OrderTotal
FROM OrderItems AS oi
JOIN Products AS p ON p.ProductID = oi.ProductID
WHERE oi.OrderID = ?
GROUP BY oi.OrderID;

-- 4.4 Calculate estimated gross profit for one order.
SELECT oi.OrderID,
       SUM((p.UnitPrice - p.UnitCost) * oi.Quantity) AS EstimatedGrossProfit
FROM OrderItems AS oi
JOIN Products AS p ON p.ProductID = oi.ProductID
WHERE oi.OrderID = ?
GROUP BY oi.OrderID;

